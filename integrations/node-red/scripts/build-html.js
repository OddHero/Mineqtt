'use strict';

// Generates nodes/devices.html (the editor part of every device node) from lib/types.js. Run it after changing the
// table: npm run build. test/html.test.js fails when the committed file is out of date.

const fs = require('fs');
const path = require('path');
const { TYPES } = require('../lib/types');

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function optionRow(o) {
    const id = `node-input-${o.name}`;
    if (o.type === 'select') {
        const opts = o.values.map(([v, l]) => `<option value="${esc(v)}">${esc(l)}</option>`).join('');
        return `    <div class="form-row"><label for="${id}">${esc(o.label)}</label><select id="${id}" style="width:70%">${opts}</select></div>`;
    }
    const kind = o.type === 'password' ? 'password' : 'text';
    return `    <div class="form-row"><label for="${id}">${esc(o.label)}</label><input type="${kind}" id="${id}" style="width:70%"></div>`;
}

function template(t) {
    return `<script type="text/html" data-template-name="${t.nodeType}">
    <div class="form-row"><label for="node-input-name"><i class="fa fa-tag"></i> Name</label><input type="text" id="node-input-name" placeholder="the device's name"></div>
    <div class="form-row"><label for="node-input-source"><i class="fa fa-random"></i> Source</label>
        <select id="node-input-source" style="width:70%"><option value="mineqtt">Minecraft device (MineQTT)</option><option value="ha">Home Assistant entity</option></select></div>
    <div class="mineqtt-src-mineqtt">
        <div class="form-row"><label for="node-input-broker"><i class="fa fa-server"></i> Broker</label><input type="text" id="node-input-broker"></div>
        <div class="form-row"><label for="node-input-device"><i class="fa fa-cube"></i> Device</label>
            <select id="node-input-device" style="width:60%"></select>
            <button type="button" class="red-ui-button mineqtt-refresh" title="Reload the list"><i class="fa fa-refresh"></i></button></div>
    </div>
    <div class="mineqtt-src-ha">
        <div class="form-row"><label for="node-input-ha"><i class="fa fa-home"></i> Server</label><input type="text" id="node-input-ha"></div>
        <div class="form-row"><label for="node-input-entity"><i class="fa fa-cube"></i> Entity</label>
            <select id="node-input-entity" style="width:60%"></select>
            <button type="button" class="red-ui-button mineqtt-refresh" title="Reload the list"><i class="fa fa-refresh"></i></button></div>
    </div>
    <div class="form-row mineqtt-hint" style="display:none"><label></label><span class="mineqtt-hint-text" style="font-size:0.9em;opacity:0.8"></span></div>
${t.options.map(optionRow).join('\n')}
    <input type="hidden" id="node-input-deviceName">
</script>`;
}

function help(t) {
    const io = [];
    if (t.inputs) io.push('<dt>Input</dt><dd>See above; <code>msg.payload</code> is the command.</dd>');
    io.push('<dt>Output</dt><dd><code>msg.payload</code> the main value or <code>TOGGLE</code> for a trigger, '
        + '<code>msg.state</code> the whole state, <code>msg.device</code> which device sent it'
        + (t.events ? `, <code>msg.event</code> / <code>msg.eventType</code> for events (${t.events.map(esc).join(', ')})` : '')
        + '.</dd>');
    return `<script type="text/html" data-help-name="${t.nodeType}">
<p>${esc(t.help)}</p>
<p>Choose a Minecraft device of this type from your MineQTT world, or a compatible Home Assistant entity
(${t.haDomains.map((d) => `<code>${d}</code>`).join(', ')}). Devices are listed from the broker's retained messages:
deploy a new broker configuration once before the list fills.</p>
<dl class="message-properties">${io.join('')}</dl>
</script>`;
}

const meta = TYPES.map((t) => ({
    nodeType: t.nodeType, label: t.label, typeIds: t.typeIds, haDomains: t.haDomains, color: t.color, icon: t.icon,
    inputs: t.inputs, options: t.options.map((o) => ({ name: o.name, type: o.type, default: o.default })),
}));

const script = `<script type="text/javascript">
(function () {
    // Generated by scripts/build-html.js from lib/types.js: do not edit by hand.
    var TYPES = ${JSON.stringify(meta, null, 1).replace(/\n\s*/g, ' ')};

    function fill(select, items, current, describe, empty) {
        select.empty();
        if (!items.length) select.append($('<option>').val('').text(empty));
        var known = false;
        items.forEach(function (it) {
            var o = $('<option>').val(it.value).text(describe(it));
            if (it.value === current) known = true;
            select.append(o);
        });
        if (current && !known) select.prepend($('<option>').val(current).text(current + ' (not seen now)'));
        select.val(current || (items[0] && items[0].value) || '');
    }

    function setup(t) {
        var defaults = {
            name: { value: '' },
            source: { value: 'mineqtt' },
            broker: { value: '', type: 'mineqtt-broker', required: false, validate: function (v) { return this.source !== 'mineqtt' || !!v; } },
            device: { value: '', validate: function (v) { return this.source !== 'mineqtt' || !!v; } },
            ha: { value: '', type: 'mineqtt-homeassistant', required: false, validate: function (v) { return this.source !== 'ha' || !!v; } },
            entity: { value: '', validate: function (v) { return this.source !== 'ha' || !!v; } },
            deviceName: { value: '' }
        };
        var credentials = {};
        t.options.forEach(function (o) {
            if (o.type === 'password') credentials[o.name] = { type: 'password' };
            else defaults[o.name] = { value: o.default };
        });
        RED.nodes.registerType(t.nodeType, {
            category: 'MineQTT',
            color: t.color,
            icon: t.icon,
            paletteLabel: t.label,
            inputs: t.inputs,
            outputs: 1,
            defaults: defaults,
            credentials: credentials,
            label: function () { return this.name || this.deviceName || t.label; },
            labelStyle: function () { return this.name || this.deviceName ? 'node_label_italic' : ''; },
            oneditprepare: function () {
                var node = this;
                var hint = $('.mineqtt-hint'), hintText = $('.mineqtt-hint-text');
                function say(text) { if (text) { hintText.text(text); hint.show(); } else hint.hide(); }
                function load() {
                    var source = $('#node-input-source').val();
                    $('.mineqtt-src-mineqtt').toggle(source === 'mineqtt');
                    $('.mineqtt-src-ha').toggle(source === 'ha');
                    say('');
                    if (source === 'mineqtt') {
                        var broker = $('#node-input-broker').val();
                        if (!broker || broker === '_ADD_') { fill($('#node-input-device'), [], node.device, null, 'choose a broker first'); return; }
                        $.getJSON('mineqtt/devices', { broker: broker, types: t.typeIds.join(',') }).done(function (r) {
                            if (r.error === 'deploy') say('Deploy the broker configuration first, then reload the list.');
                            else if (!r.connected) say('The broker is not connected.');
                            var items = (r.devices || []).map(function (d) {
                                return { value: d.key, d: d };
                            });
                            fill($('#node-input-device'), items, node.device, function (it) {
                                var d = it.d, where = [d.room, d.bridgeId].filter(Boolean).join(', ');
                                return d.name + (where ? ' (' + where + ')' : '') + (d.typeId ? '' : ' [type unknown]') + (d.available === false ? ' [offline]' : '');
                            }, 'no ' + t.label + ' found');
                        });
                    } else {
                        var server = $('#node-input-ha').val();
                        if (!server || server === '_ADD_') { fill($('#node-input-entity'), [], node.entity, null, 'choose a server first'); return; }
                        $.getJSON('mineqtt/entities', { server: server, domains: t.haDomains.join(',') }).done(function (r) {
                            if (r.error === 'deploy') say('Deploy the Home Assistant configuration first, then reload the list.');
                            else if (!r.connected) say('Home Assistant is not connected.');
                            var items = (r.entities || []).map(function (e) { return { value: e.entity_id, e: e }; });
                            fill($('#node-input-entity'), items, node.entity, function (it) {
                                return it.e.name + (it.e.area ? ' (' + it.e.area + ')' : '') + ' - ' + it.e.entity_id;
                            }, 'no ' + t.haDomains.join('/') + ' entity found');
                        });
                    }
                }
                $('#node-input-source').on('change', load);
                $('#node-input-broker').on('change', load);
                $('#node-input-ha').on('change', load);
                $('.mineqtt-refresh').on('click', load);
                load();
            },
            oneditsave: function () {
                var source = $('#node-input-source').val();
                var sel = source === 'ha' ? $('#node-input-entity option:selected') : $('#node-input-device option:selected');
                var text = sel.val() ? sel.text().replace(/ \\(.*$/, '').replace(/ - .*$/, '').replace(/ \\[.*$/, '') : '';
                $('#node-input-deviceName').val(text);
            }
        });
    }
    TYPES.forEach(setup);
})();
</script>`;

const out = [
    '<!-- Generated by scripts/build-html.js from lib/types.js: do not edit by hand. -->',
    script,
    ...TYPES.map(template),
    ...TYPES.map(help),
    '',
].join('\n');

const target = path.join(__dirname, '..', 'nodes', 'devices.html');
if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (current !== out) { console.error('nodes/devices.html is out of date: run npm run build'); process.exit(1); }
} else {
    fs.writeFileSync(target, out);
    console.log(`wrote ${path.relative(process.cwd(), target)} (${TYPES.length} nodes)`);
}
